// Extracts the three prototype games (Reaction Test, Tap Rush, Aim Trainer) from script 027.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const root = join(import.meta.dir, "..");
const L = readFileSync(join(root, "_orig/027_script.js"), "utf8").split("\n");
let body = L.slice(178, 259).join("\n"); // wbLaunchProto
const names = L.slice(152, 157).join("\n");
body = body
  .replace(/\bwbRecordGameScore\b/g, "recordGameScore").replace(/\bwbTrackGamePlayed\b/g, "trackGamePlayed").replace(/\bwbAddCoins\b/g, "addCoins")
  .replace("overlay.classList.remove('on'); overlay.innerHTML=''; try{", "overlay.classList.remove('on'); overlay.innerHTML=''; engineClosed(); try{")
  .replace("overlay.classList.add('on');", "openEngine(function(){});");
const out = `// @ts-nocheck
// Prototype games (generated by tools/convert-protos.ts from the original app; logic verbatim).
import { recordGameScore, trackGamePlayed, addCoins } from "../core/profile";
import { WB_SOUND } from "../core/sound";
import { openEngine, engineClosed } from "../core/overlay";

${names.replace("var WB_PROTOS =", "var WB_PROTOS =")}
${body.replace("function wbLaunchProto(key){", "export function wbLaunchProto(key){")}
`;
writeFileSync(join(root, "src/arcade/protos.ts"), out);
console.log("protos written");
