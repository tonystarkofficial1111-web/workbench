// Extracts the car games (Drift King, F1 Cockpit, Rally, Thinking challenge, CAR hub, six car cabinets) from script 029
// into src/arcade/legacy029.ts. Logic is verbatim; the shared overlay helper is re-implemented for the React shell.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const L = readFileSync(join(root, "_orig/029_script.js"), "utf8").split("\n");
const range = (a: number, b: number) => L.slice(a - 1, b).join("\n"); // 1-based inclusive

const pieces = [
  range(953, 962), // KeyTracker
  range(704, 884), // CAR hub, rally, thinking
  range(1220, 1351), // Drift King
  range(1854, 2642), // F1 Cockpit
  range(2776, 2814), // six car cabinets
];

const header = `// @ts-nocheck
// Car games (CAR hub, Drift King, F1 Cockpit, Rally Stage, Engineering challenge, six car cabinets).
// Generated by tools/convert-029.ts from the original app; engine logic is verbatim.
import { getProfile, recordGameScore, trackGamePlayed, saveProfile, checkAchievements } from "../core/profile";
import { openEngine, engineClosed } from "../core/overlay";

function L(m){ try{ (window.__wb519Log = window.__wb519Log || []).push(m); }catch(e){} }

/** Shared overlay shell (original ovOpen). The Close button is wired to the original close closure, as before. */
function ovOpen(title, sub, bodyHTML){
  var ov = document.getElementById('ac-overlay'); if(!ov) return null;
  openEngine(function(){});
  try{ if(ov.requestFullscreen) ov.requestFullscreen().catch(function(){}); }catch(e){}
  ov.innerHTML = '';
  var shell = document.createElement('div'); shell.className = 'g519-shell';
  shell.innerHTML = '<h3>' + title + '</h3>' + (sub ? '<p class="g519-sub">' + sub + '</p>' : '') + bodyHTML +
    '<div class="g519-foot"><button class="type-btn ghost" id="g519-close">Close</button></div>';
  ov.appendChild(shell);
  var closed = false;
  function close(){
    if(closed) return; closed = true;
    ov.classList.remove('on'); ov.innerHTML = ''; engineClosed();
    try{ if(document.fullscreenElement) document.exitFullscreen().catch(function(){}); }catch(e){}
  }
  document.getElementById('g519-close').addEventListener('click', close);
  return { shell: shell, ov: ov, close: close };
}
function endGame(key, mode, score){
  try{ trackGamePlayed(key); recordGameScore(key, mode, score); saveProfile(); checkAchievements(); }catch(e){ L('save err: ' + e.message); }
}
function wbPlayAgain(o, fn, score){
  try{
    if(!o || !o.shell) return;
    var old = o.shell.querySelector('.wb-play-again-row'); if(old) old.remove();
    var row = document.createElement('div'); row.className = 'wb-play-again-row'; row.style.cssText = 'text-align:center;margin:10px 0 0';
    var msg = document.createElement('p'); msg.className = 'g519-sub'; msg.style.cssText = 'text-align:center;margin:0 0 8px'; msg.textContent = 'Game over' + (score !== undefined ? ' · score: ' + score : '');
    var btn = document.createElement('button'); btn.type = 'button'; btn.className = 'type-btn'; btn.textContent = 'Play Again';
    row.appendChild(msg); row.appendChild(btn);
    var foot = o.shell.querySelector('.g519-foot'); o.shell.insertBefore(row, foot || null);
    btn.addEventListener('click', function(){ row.remove(); try{ fn(); }catch(err){ L('play again err: ' + err.message); } });
  }catch(e){}
}

`;

let body = pieces.join("\n\n").replace(/\bwbProfile\b/g, "getProfile()");
// wbTrackGamePlayed & friends used directly inside pieces
body = body
  .replace(/\bwbTrackGamePlayed\b/g, "trackGamePlayed")
  .replace(/\bwbRecordGameScore\b/g, "recordGameScore")
  .replace(/\bwbSaveProfile\b/g, "saveProfile")
  .replace(/\bwbCheckAchievements\b/g, "checkAchievements");

// The original wrote these through a comma expression after a call (implicit globals in sloppy mode).
body = body
  .replace("kt.install(),x=310,score=0,gates=0,gateX=310,raf=null,dead=false;", "kt.install();var x=310,score=0,gates=0,gateX=310,raf=null,dead=false;")
  .replace("kt.install(),car={x:105,y:290,a:0,v:0},raf=null,done=false,moves=0;", "kt.install();var car={x:105,y:290,a:0,v:0},raf=null,done=false,moves=0;");

const footer = `

export const CAR_LAUNCHERS = {
  carHub: launchCarHub,
  pitstop532: launchPitStopPro,
  reactionlights532: launchReactionLights,
  apexhunter532: launchApexHunter,
  parking532: launchParkingMaster,
  draglaunch532: launchDragLaunch,
  setuplab532: launchSetupLab,
};
`;
writeFileSync(join(root, "src/arcade/legacy029.ts"), header + body + footer);
console.log("legacy029.ts written", (header + body + footer).length);
