// Extracts PIXEL DUEL (two-player local game) from script 028.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const root = join(import.meta.dir, "..");
const L = readFileSync(join(root, "_orig/028_script.js"), "utf8").split("\n");
// var DUEL ... wbDuelKeys (lines 249-364), skipping the bubble renderer (it only rendered the tile)
let body = L.slice(248, 364).join("\n");
const s = body.indexOf("function wbDuelRenderBubble()");
const e = body.indexOf("function wbDuelLaunch()");
body = body.slice(0, s) + body.slice(e);
body = body
  .replace(/\bwbTrackGamePlayed\b/g, "trackGamePlayed").replace(/\bwbRecordGameScore\b/g, "recordGameScore")
  .replace(/\bwbSaveProfile\b/g, "saveProfile").replace(/\bwbCheckAchievements\b/g, "checkAchievements")
  .replace(/typeof WB_SOUND!=='undefined'&&WB_SOUND\.coin/g, "WB_SOUND.coin")
  .replace("overlay.classList.add('on');", "openEngine(function(){});")
  .replace("if(overlay){ overlay.classList.remove('on'); overlay.innerHTML=''; }", "if(overlay){ overlay.classList.remove('on'); overlay.innerHTML=''; engineClosed(); }")
  .replace(/L\('duel save err: '\+e\.message\)/, "console.error(e)");
const out = `// @ts-nocheck
// PIXEL DUEL (generated by tools/convert-duel.ts from the original app; logic verbatim).
import { recordGameScore, trackGamePlayed, saveProfile, checkAchievements } from "../core/profile";
import { WB_SOUND } from "../core/sound";
import { openEngine, engineClosed } from "../core/overlay";

${body}

let keysInstalled = false;
export function launchPixelDuel(){
  if(!keysInstalled){
    keysInstalled = true;
    document.addEventListener('keydown', wbDuelKeys(true));
    document.addEventListener('keyup', wbDuelKeys(false));
  }
  wbDuelLaunch();
}
`;
writeFileSync(join(root, "src/arcade/pixelDuel.ts"), out);
console.log("duel written");
