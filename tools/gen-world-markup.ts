// Builds src/world/markup.ts: the Block World markup that exists BEFORE the engine boots
// (original static markup + the two button columns, instructions button and recorder button that small patch scripts added).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const page = readFileSync(join(root, "_orig/page.html"), "utf8");
const m = page.match(/<section id="tab-world" class="tab">([\s\S]*?)<\/section>/);
if (!m) throw new Error("world section not found");
let inner = m[1]!;

// Pieces that were moved into columns by the 5.49.1 layout patch.
const take = (re: RegExp) => {
  const mm = inner.match(re);
  if (!mm) throw new Error("not found: " + re);
  inner = inner.replace(mm[0], "");
  return mm[0].trim();
};
const modeToggle = take(/<button id="mode-toggle"[^>]*><\/button>\s*/);
const worldStatus = take(/<div id="world-status"><\/div>\s*/);
const perfBox = take(/<div id="perf-box">[\s\S]*?<\/div><\/div>\s*/).replace("FPS: --", "FPS: --");
const shaderToggle = take(/<button id="shader-toggle"[^>]*>[^<]*<\/button>\s*/);
const rainBox = take(/<div id="rain-box">[\s\S]*?<\/div>\s*<div id="rain-pct">[^<]*<\/div><\/div>\s*/);
const followKing = take(/<button id="follow-king-btn"[^>]*>[^<]*<\/button>\s*/);
const saveLoad = take(/<div id="save-load">[\s\S]*?<\/div>\s*/);

const out =
  inner.trim() +
  `<div id="bw-right-col">${perfBox}${shaderToggle}${rainBox}${followKing}<button id="bw-instr-btn" type="button">Instructions</button></div>` +
  `<div id="bw-left-col">${modeToggle}${worldStatus}${saveLoad}</div>`; // the recorder script adds its own button + toast

writeFileSync(join(root, "src/world/markup.ts"), "// Generated by tools/gen-world-markup.ts\nexport const WORLD_MARKUP = " + JSON.stringify(out) + ";\n");
console.log("world markup", out.length);
