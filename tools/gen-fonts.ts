// Generates src/styles/00-fonts.css with the three font families inlined as data: URIs.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const root = join(import.meta.dir, "..");
const fonts: [string, number, string][] = [
  ["Inter", 400, "@fontsource/inter/files/inter-latin-400-normal.woff2"],
  ["Inter", 500, "@fontsource/inter/files/inter-latin-500-normal.woff2"],
  ["Inter", 600, "@fontsource/inter/files/inter-latin-600-normal.woff2"],
  ["Space Grotesk", 500, "@fontsource/space-grotesk/files/space-grotesk-latin-500-normal.woff2"],
  ["Space Grotesk", 700, "@fontsource/space-grotesk/files/space-grotesk-latin-700-normal.woff2"],
  ["Dancing Script", 700, "@fontsource/dancing-script/files/dancing-script-latin-700-normal.woff2"],
];
let css = "/* generated by tools/gen-fonts.ts */\n";
for (const [fam, w, p] of fonts) {
  const b64 = readFileSync(join(root, "node_modules", p)).toString("base64");
  css += `@font-face{font-family:'${fam}';font-weight:${w};font-style:normal;font-display:swap;src:url(data:font/woff2;base64,${b64}) format('woff2')}\n`;
}
writeFileSync(join(root, "src/styles/00-fonts.css"), css);
console.log("fonts css", css.length);
